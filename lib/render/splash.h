/*
 * splash.h — the boot splash: a small bitmap centred on a plain screen.
 *
 * Why: some HDMI capture cards (the ShadowCast 2) are slow to lock onto a
 * fresh boot's nearly-black screen, but lock at once onto a busy picture.
 * So the first seconds after power-on show this instead of the terminal
 * (devlog 032). The app swaps splash_scanline in for render_scanline with
 * video_set_scanline, so the text renderer's hot path doesn't change.
 *
 * Layering: pure module (hardware-free; host-testable), like render.
 *
 * The image is SPLASH_WIDTH x SPLASH_HEIGHT, 4 bits a pixel indexing
 * splash_palette (RGB565), two pixels a byte with the left one in the low
 * nibble. Palette entry 0 is the background around it. Both arrays are
 * generated by tools/splash.py from assets/splash.png (splash_image.c).
 */
#ifndef SPLASH_H
#define SPLASH_H

#include <stddef.h>
#include <stdint.h>

#define SPLASH_WIDTH	192
#define SPLASH_HEIGHT	108
#define SPLASH_COLOURS	16

extern const uint16_t splash_palette[SPLASH_COLOURS];
extern const uint8_t  splash_pixels[SPLASH_HEIGHT * SPLASH_WIDTH / 2];

/*
 * Where the image lands on a screen: its top-left corner and scale (1, or
 * 2 once the screen is 720 lines). Filled by splash_layout, read by the
 * scanline. The palette and pixels are copied into RAM so the scanline
 * never reads XIP flash from the render IRQ (a cache miss there stalls
 * the line); the pixels borrow a buffer that isn't in use yet at boot
 * (app.c lends SET-UP's screen) and is wiped when the splash ends.
 */
struct splash {
	uint16_t	 width;		/* screen */
	uint16_t	 height;
	uint16_t	 left;		/* image's first column, even */
	uint16_t	 top;		/* image's first line */
	uint8_t		 scale;
	uint32_t	 background;	/* palette[0], twice (two pixels) */
	uint16_t	 palette[SPLASH_COLOURS];
	const uint8_t	*pixels;	/* the borrowed copy, or flash's */
};

/* Bytes of RAM the pixels need (splash_layout's `ram`). */
#define SPLASH_PIXEL_BYTES	(SPLASH_HEIGHT * SPLASH_WIDTH / 2)

/*
 * Lay the image out on a width x height screen, copying the pixels into
 * `ram` (ram_bytes long, 4-byte aligned) if it's at least
 * SPLASH_PIXEL_BYTES; otherwise they're read from flash.
 */
void	splash_layout(struct splash *splash, unsigned width, unsigned height,
	    void *ram, size_t ram_bytes);

/* video_scanline_fn-compatible: ctx is the struct splash. */
void	splash_scanline(uint16_t *pixels, unsigned line, void *ctx);

#endif /* SPLASH_H */
