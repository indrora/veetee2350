/*
 * splash.h — the boot splash: a bitmap centred on a plain screen.
 *
 * Why: some HDMI capture cards (the ShadowCast 2) are slow to lock onto a
 * fresh boot's nearly-black screen, but lock at once onto a busy picture.
 * So the first seconds after power-on show this instead of the terminal
 * (devlog 032). The app swaps splash_scanline in for render_scanline with
 * video_set_scanline, so the text renderer's hot path doesn't change.
 *
 * Layering: pure module (hardware-free; host-testable), like render.
 *
 * The image is SPLASH_WIDTH x SPLASH_HEIGHT RGB565 pixels, row-major, in
 * flash: 128 KB, read straight from there, a line at a time. That's a
 * stream of XIP cache misses (the image is 8x the cache), which the text
 * renderer could never afford, but the splash is one copy loop for 3 s:
 * 512 bytes a line from QSPI is well inside the line budget of every
 * mode. splash_background, the image's top-right pixel, fills the rest of
 * the screen. Both are generated by tools/splash.py from
 * assets/splash.png (splash_image.c).
 */
#ifndef SPLASH_H
#define SPLASH_H

#include <stdint.h>

#define SPLASH_WIDTH	256
#define SPLASH_HEIGHT	256

extern const uint16_t splash_background;
extern const uint16_t splash_pixels[SPLASH_HEIGHT * SPLASH_WIDTH];

/*
 * Where the image lands on a screen: its top-left corner and scale (1, or
 * 2 once the screen is 720 lines). Filled by splash_layout, read by the
 * scanline.
 */
struct splash {
	uint16_t	 width;		/* screen */
	uint16_t	 height;
	uint16_t	 left;		/* image's first column, even */
	uint16_t	 top;		/* image's first line */
	uint8_t		 scale;
	uint32_t	 background;	/* splash_background, twice */
};

/* Lay the image out on a width x height screen. */
void	splash_layout(struct splash *splash, unsigned width, unsigned height);

/* video_scanline_fn-compatible: ctx is the struct splash. */
void	splash_scanline(uint16_t *pixels, unsigned line, void *ctx);

#endif /* SPLASH_H */
